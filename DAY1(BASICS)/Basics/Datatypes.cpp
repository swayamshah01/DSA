#include <iostream>
using namespace std;

int main() {
    // Integer types
    int age = 25;
    short temperature = -10;
    long population = 1000000000;
    long long bigNumber = 9223372036854775807LL;
    
    // Unsigned integer
    unsigned int count = 100;
    
    // Floating point types
    float pi = 3.14f;
    double salary = 50000.50;
    
    // Character type
    char grade = 'A';
    
    // Boolean type
    bool isActive = true;
    
    // Display values
    cout << "Integer: " << age << endl;
    cout << "Short: " << temperature << endl;
    cout << "Long: " << population << endl;
    cout << "Long Long: " << bigNumber << endl;
    cout << "Unsigned Int: " << count << endl;
    cout << "Float: " << pi << endl;
    cout << "Double: " << salary << endl;
    cout << "Char: " << grade << endl;
    cout << "Boolean: " << isActive << endl;
    
    return 0;
}